// The Community Hub's dialogs: its rules (agreed to once, before the first
// upload, and readable from the account menu), the publish confirm, and the picker that chooses which of your Fakémon
// to publish or to replace a listing with.

import { useMemo, useState } from 'react';
import { api, state } from '../../core/app.ts';
import { Icon } from '../components/Icon.tsx';
import { Modal } from '../components/Modal.tsx';
import { registerDialog, type DialogProps } from '../dialogs.tsx';
import type { Fakemon } from '../types.ts';

// ==================== rules ====================

type RulesProps = DialogProps<{ requireAgreement?: boolean; offerOpen?: boolean; monName?: string; onAccept?: ((choice?: { open: boolean }) => void) | null }>;

const RULES: Array<[string, string]> = [
    ['We strictly do not allow AI art.', 'Artwork must be drawn by a human being. Anything generated by an AI image tool, or traced, painted over, or touched up from a generated image, will be removed. Repeat uploads are grounds for a permanent ban. If you did not draw it, credit the artist who did.'],
    ['No NSFW or sexual content.', 'This includes artwork, names, descriptions, cries, and other uploaded content.'],
    ['No inappropriate or offensive names.', ''],
    ['No spam.', 'Do not flood the Community Hub with repeated or low-effort posts.'],
    ['No harassment, threats, hate, or discrimination.', ''],
    ['No impersonation.', 'Do not pretend to be another user, creator, staff member, company, or organization.'],
    ['No scams, misleading content, or advertising.', ''],
    ['Only share content you have permission to use.', ''],
    ['Do not upload malicious or harmful files.', '']
];

function RulesList() {
    return (
        <>
            <p>Keep the Community Hub friendly, creative, and safe for everyone.</p>
            <ul>{RULES.map(([b, rest]) => <li key={b}><strong>{b}</strong>{rest ? ` ${rest}` : ''}</li>)}</ul>
            <p>Breaking these rules may result in content removal, account termination, and a permanent ban from the Community Hub and Woogidex.</p>
        </>
    );
}

/**
 * The Community Rules. Read from the menu, it's just the rules. Before an
 * upload it asks you to agree, once: after that, publishing shows a short
 * confirm (with the "make it open" choice) and the rules fold away behind a link.
 */
function CommunityRulesDialog({ close, requireAgreement = false, offerOpen = false, monName = '', onAccept = null }: RulesProps) {
    const already = !!api.hasAcceptedCommunityRules?.();
    const [agreed, setAgreed] = useState(already);
    const [showRules, setShowRules] = useState(!already);
    // publishing: whether to make it open (off unless they choose it)
    const [open, setOpen] = useState(false);
    const asking = requireAgreement || !!onAccept;
    function accept() {
        if (!agreed) { api.showToast?.('Please agree to the Community Rules first.', 'warning'); return; }
        api.markCommunityRulesAccepted?.();
        close();
        onAccept?.({ open: offerOpen && open });
    }
    const title = offerOpen && already ? (monName ? `Publish ${monName}` : 'Publish to the Community Hub')
        : requireAgreement ? 'Community Rules Before Publishing' : 'Community Rules';
    return (
        <Modal onClose={close} className="policy-modal community-rules-modal" labelledBy="community-rules-title" title={title}>
            <div className="modal-body policy-body">
                {offerOpen && already && (
                    <p className="community-publish-lead">It goes up as a snapshot: edits you make later stay private until you update the listing. Its evolution stages, megas and formes go up with it.</p>
                )}
                {showRules ? <RulesList /> : (
                    <button type="button" className="community-rules-peek" onClick={() => setShowRules(true)}>
                        <Icon name="check-circle" size={16} /><span>You've agreed to the Community Rules.</span><u>Read them again</u>
                    </button>
                )}
                {offerOpen && (
                    <label className={`community-open-choice${open ? ' is-on' : ''}`}>
                        <input type="checkbox" checked={open} onChange={e => setOpen(e.target.checked)} />
                        <span className="community-open-choice-text">
                            <strong><Icon name="lock-open" size={15} /> Make it open</strong>
                            <span>Share it freely: its artwork shows without the art shield, anyone can export it, and its page opens for people who aren't signed in and in search results. Only this Fakémon is opened, nothing else of yours. You can close it again later from its page, but copies people already exported stay out there.</span>
                        </span>
                    </label>
                )}
                {asking ? (
                    <div className="policy-actions">
                        {!already && (
                            <div className="policy-check-row" style={{ display: 'flex' }}>
                                <label className="auth-terms-check">
                                    <input type="checkbox" checked={agreed} onChange={e => setAgreed(e.target.checked)} />
                                    <span>I have read and agree to the Community Rules.</span>
                                </label>
                            </div>
                        )}
                        <button type="button" className="btn btn-secondary" onClick={close}>Cancel</button>
                        <button type="button" className="btn btn-primary" disabled={!agreed} onClick={accept}>
                            {already
                                ? (offerOpen ? <><Icon name="upload" size={14} /> {open ? 'Publish as open' : 'Publish'}</> : 'Continue')
                                : (offerOpen && open ? 'I Agree and Publish as Open' : 'I Agree and Continue')}
                        </button>
                    </div>
                ) : !already ? (
                    <div className="policy-actions">
                        <div className="policy-check-row" style={{ display: 'flex' }}>
                            <label className="auth-terms-check">
                                <input type="checkbox" checked={agreed} onChange={e => setAgreed(e.target.checked)} />
                                <span>I have read and agree to the Community Rules.</span>
                            </label>
                        </div>
                        <button type="button" className="btn btn-primary" disabled={!agreed} onClick={accept}>I Agree</button>
                    </div>
                ) : null}
            </div>
        </Modal>
    );
}

// ==================== pick one of your Fakémon ====================

type SortKey = 'created' | 'name' | 'number' | 'bst' | 'updated';
type PickerProps = DialogProps<{ mode: 'publish' | 'update'; targetId?: string | null; preselectId?: string }>;

const bst = (f: Fakemon): number => Number(api.getFakemonBST?.(f)) || 0;
const dex = (f: Fakemon) => { const n = parseInt(String(f.number || '').replace(/^#/, ''), 10); return Number.isFinite(n) ? n : Number.POSITIVE_INFINITY; };
const SORTS: Array<[SortKey, string]> = [['created', 'Date added'], ['updated', 'Last edited'], ['name', 'Name'], ['number', 'Dex no.'], ['bst', 'BST']];

function CommunityPickerDialog({ close, mode, targetId = null, preselectId = '' }: PickerProps) {
    const collection: Fakemon[] = (state.fakemonDB || []).filter(f => !f.pendingVanilla);
    const [search, setSearch] = useState('');
    const [sortBy, setSortBy] = useState<SortKey>('created');
    const [order, setOrder] = useState<'asc' | 'desc'>('desc');
    const [selected, setSelected] = useState(() => (collection.some(f => String(f.id) === String(preselectId)) ? String(preselectId) : ''));
    const publishing = mode === 'publish';
    const target = !publishing && targetId ? (api.communityState?.().mons || []).find((m: any) => String(m.id) === String(targetId)) : null;

    const shown = useMemo(() => {
        const q = search.trim().toLowerCase();
        const dir = order === 'asc' ? 1 : -1;
        return collection
            .filter(f => !q || String(f.name || '').toLowerCase().includes(q) || String(f.number || '').toLowerCase().includes(q)
                || String(f.type1 || '').toLowerCase() === q || String(f.type2 || '').toLowerCase() === q)
            .sort((a, b) => {
                if (sortBy === 'name') return String(a.name || '').localeCompare(String(b.name || '')) * dir;
                if (sortBy === 'number') return (dex(a) - dex(b)) * dir;
                if (sortBy === 'bst') return (bst(a) - bst(b)) * dir;
                if (sortBy === 'updated') return ((Number(a.updatedAt) || 0) - (Number(b.updatedAt) || 0)) * dir;
                return ((Number(a.createdAt) || 0) - (Number(b.createdAt) || 0)) * dir;
            });
    }, [collection, search, sortBy, order]);
    const current = collection.find(f => String(f.id) === selected);

    function confirm() {
        if (!selected) { api.showToast?.('Choose a Fakémon from your collection first.', 'warning'); return; }
        close();
        if (publishing) { api.publishFakemon(selected); return; }
        if (!targetId) { api.showToast?.('That listing could not be found.', 'error'); return; }
        api.updatePublishedMon(targetId, selected);
    }

    return (
        <Modal onClose={close} className="community-update-modal" title={publishing ? 'Publish a Fakémon' : 'Update this listing'}>
            <div className="modal-body community-update-modal-body">
                <p className="community-update-help">
                    {publishing
                        ? 'Pick one from your collection. Its evolution stages, megas and formes go up with it as one post.'
                        : <>Pick the Fakémon whose current version should replace {target?.name ? <strong>{target.name}</strong> : 'this listing'}. Likes and comments stay.</>}
                </p>
                <div className="community-update-controls">
                    <label className="community-update-search">
                        <Icon name="search" size={16} />
                        <input type="search" placeholder="Search by name, number or type" value={search} onChange={e => setSearch(e.target.value)} autoFocus />
                    </label>
                    <div className="community-update-sort" role="group" aria-label="Sort">
                        <select value={sortBy} onChange={e => setSortBy(e.target.value as SortKey)} aria-label="Sort by">
                            {SORTS.map(([k, l]) => <option key={k} value={k}>{l}</option>)}
                        </select>
                        <button type="button" className="btn btn-secondary btn-icon btn-sm" onClick={() => setOrder(o => o === 'asc' ? 'desc' : 'asc')}
                            aria-label={order === 'asc' ? 'Ascending' : 'Descending'} title={order === 'asc' ? 'Ascending' : 'Descending'}>
                            <Icon name={order === 'asc' ? 'bars-arrow-up' : 'bars-arrow-down'} size={16} />
                        </button>
                    </div>
                </div>
                <div className="community-update-collection-grid" role="listbox" aria-label="Your Fakémon">
                    {shown.length ? shown.map(f => {
                        const id = String(f.id);
                        const number = f.number ? `#${String(f.number).replace(/^#/, '')}` : '';
                        const total = bst(f);
                        const on = id === selected;
                        return (
                            <button key={id} type="button" role="option" aria-selected={on} className={`community-update-mon-card${on ? ' selected' : ''}`}
                                onClick={() => setSelected(id)} onDoubleClick={() => { setSelected(id); setTimeout(confirm); }}>
                                {on && <span className="community-update-check"><Icon name="check" size={13} /></span>}
                                <div className="community-update-mon-art">
                                    {f.artwork
                                        ? <img src={f.artwork} alt="" loading="lazy" decoding="async" />
                                        : <img className="no-art-placeholder" src="assets/no_art_placeholder.png" alt="" />}
                                </div>
                                <div className="community-update-mon-info">
                                    <strong>{f.name || 'Unnamed Fakémon'}</strong>
                                    <span className="community-update-mon-types">
                                        {[f.type1, f.type2].filter(Boolean).map(t => <span key={t} className={`type-pill type-${String(t).toLowerCase()}`}>{t}</span>)}
                                    </span>
                                    <small>{number}{number && total ? ' · ' : ''}{total ? `BST ${total}` : ''}</small>
                                </div>
                            </button>
                        );
                    }) : (
                        <div className="community-update-empty">
                            <Icon name={collection.length ? 'magnifying-glass' : 'sparkles'} size={22} />
                            <p>{collection.length ? 'No Fakémon match your search.' : 'Your collection is empty. Make a Fakémon first!'}</p>
                        </div>
                    )}
                </div>
                <div className="community-update-actions">
                    <div className="community-update-selected">
                        {current ? <><span className="community-update-selected-label">Selected</span><strong>{current.name || 'Unnamed Fakémon'}</strong></> : <span>Nothing picked yet</span>}
                    </div>
                    <div className="community-update-action-buttons">
                        <button className="btn btn-secondary" type="button" onClick={close}>Cancel</button>
                        <button className="btn btn-primary" type="button" disabled={!current} onClick={confirm}>
                            {publishing ? <><Icon name="upload" size={14} /> Next</> : <><Icon name="refresh-cw" size={14} /> Update listing</>}
                        </button>
                    </div>
                </div>
            </div>
        </Modal>
    );
}

registerDialog('community-rules', CommunityRulesDialog);
registerDialog('community-picker', CommunityPickerDialog);
